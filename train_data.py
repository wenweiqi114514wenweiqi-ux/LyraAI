# 2. 特殊 token 与词表构建（字符级 tokenizer）
# ============================================================
SPECIAL_TOKENS = {
    "<user>": 1,   # 用户话术开始
    "<asst>": 2,   # 助手回复开始
    "<end>": 3,    # 助手回答结束
}
PAD_ID = 0         # 未知字符 / 填充

def tokenize(text):
    """词级分词（jieba）：一个中文词 / 英文词 / 数字 / 标点 = 一个 token"""
    return list(jieba.lcut(text))


def build_vocab(conversations, texts=None):
    """从对话文本 + 正式材料文本中收集出现的词，构建 token->id / id->token 映射"""
    all_toks = set()
    for turns in conversations:
        for _, text in turns:
            all_toks.update(tokenize(text))
    if texts:
        for t in texts:
            all_toks.update(tokenize(t))

    toks = sorted(all_toks)
    # 词 id 从 4 开始（0-3 留给 pad 和特殊 token）
    token2idx = {t: i + 4 for i, t in enumerate(toks)}
    idx2token = {i + 4: t for i, t in enumerate(toks)}
    vocab_size = 4 + len(toks)

    # 保证不超过模型设定的词表容量（lyra_model 里 vocab_size=4096）
    assert vocab_size <= 4096, f"词表 {vocab_size} 超出模型容量 4096，需调大模型"

    # 反向：id -> token，特殊 token 也在里面
    for tok, idx in SPECIAL_TOKENS.items():
        idx2token[idx] = tok

    return token2idx, idx2token, vocab_size


def encode(text, token2idx):
    """把一段文本分词后编码成 id 列表（未登录词用 PAD_ID=0）"""
    return [token2idx.get(t, PAD_ID) for t in tokenize(text)]


def build_samples(conversations, char2idx):
    """
    把每段对话编码成 (id序列, 助手部分掩码) 的样本。
    id序列格式: <user> 用户话术 <asst> 助手回复 <end> <user> 下一轮... <end>
    asst_mask[t] = 1 表示位置 t 属于"助手应该接话"的区域（t 处需预测 t+1）
    """
    samples = []
    for turns in conversations:
        ids = []
        asst_mask = []
        for role, text in turns:
            if role == "u":
                ids.append(SPECIAL_TOKENS["<user>"])
                asst_mask.append(0)
                for ch_id in encode(text, char2idx):
                    ids.append(ch_id)
                    asst_mask.append(0)
            else:  # role == 'a'
                ids.append(SPECIAL_TOKENS["<asst>"])
                asst_mask.append(1)          # <asst> 本身就开始进入应接话区域
                for ch_id in encode(text, char2idx):
                    ids.append(ch_id)
                    asst_mask.append(1)
                ids.append(SPECIAL_TOKENS["<end>"])
                asst_mask.append(1)          # <end> 也在应接话区域
        samples.append((ids, asst_mask))
    return samples


def build_text_samples(texts, char2idx):
    """
    正式材料样本（模拟预训练）：整段连续文本都参与预测下一个字。
    每个样本为 (id序列, mask)，mask 全 1，表示整段都要学。
    """
    samples = []
    for t in texts:
        ids = encode(t, char2idx)
        if len(ids) < 2:
            continue
        samples.append((ids, [1] * len(ids)))
    return samples


def decode(ids, idx2char):
    """把 id 序列还原成文本（用于看模型生成了什么）"""
    return "".join(idx2char.get(i, "?") for i in ids)


